import {createClient} from '@supabase/supabase-js'
const db=()=>createClient(process.env.SUPABASE_URL||process.env.VITE_SUPABASE_URL,process.env.SUPABASE_SERVICE_KEY,{auth:{persistSession:false}})
const val=x=>String(x||'').trim()
export default async function handler(req,res){
 if(req.method!=='POST')return res.status(405).json({error:'Method not allowed'})
 if(!process.env.SUPABASE_SERVICE_KEY)return res.status(503).json({error:'Server database credentials missing'})
 const token=(req.headers.authorization||'').replace(/^Bearer\s+/i,'')
 if(!token)return res.status(401).json({error:'Sign in required'})
 const client=db()
 const {data:{user},error:authError}=await client.auth.getUser(token)
 if(authError||!user)return res.status(401).json({error:'Invalid session'})
 const {data:admin}=await client.from('users').select('role').eq('id',user.id).maybeSingle()
 if(admin?.role!=='admin')return res.status(403).json({error:'Admin required'})
 const zip=val(req.body?.zip),city=val(req.body?.city),state=val(req.body?.state).toUpperCase()
 if(!/^\d{5}$/.test(zip)||!city||!/^[A-Z]{2}$/.test(state))return res.status(400).json({error:'City, state and five-digit ZIP required'})
 const {data:properties,error:pError}=await client.from('properties').select('city,state,zip').eq('state',state).eq('zip',zip).limit(200)
 if(pError)return res.status(500).json({error:pError.message})
 if(!properties?.some(p=>val(p.city).toLowerCase()===city.toLowerCase()))return res.status(400).json({error:'ZIP and city must match an existing property'})
 const {data:agents,error:aError}=await client.from('closing_agents').select('*').eq('state',state).eq('active',true).limit(2000)
 if(aError)return res.status(500).json({error:aError.message})
 const exact=(agents||[]).filter(a=>val(a.zip).slice(0,5)===zip)
 const nearby=(agents||[]).filter(a=>val(a.city).toLowerCase()===city.toLowerCase()&&!exact.some(b=>b.id===a.id))
 return res.status(200).json({zip,city,state,source:'saved-directory',matches:[...exact,...nearby],exactZipCount:exact.length,needsHudLookup:exact.length+nearby.length===0,message:'Matched against saved closing attorneys. HUD live directory lookup is not connected.'})
}
